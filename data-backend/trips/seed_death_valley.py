def create_death_valley_trip(user):
    from .models import Trip, TripDay, TripStop

    existing = Trip.objects.filter(
        user=user,
        title=DEATH_VALLEY_2026['title'],
        start_date=DEATH_VALLEY_2026['start_date'],
    ).first()
    if existing:
        return existing, False

    trip = Trip.objects.create(
        user=user,
        title=DEATH_VALLEY_2026['title'],
        start_date=DEATH_VALLEY_2026['start_date'],
        end_date=DEATH_VALLEY_2026['end_date'],
    )
    for i, day_data in enumerate(DEATH_VALLEY_2026['days']):
        day = TripDay.objects.create(
            user=user,
            trip=trip,
            date=day_data['date'],
            title=day_data['title'],
            sort_order=i,
        )
        for j, stop in enumerate(day_data['stops']):
            TripStop.objects.create(
                user=user,
                day=day,
                text=stop['text'],
                description=stop.get('description') or '',
                loc=stop.get('loc') or '',
                cat=stop.get('cat') or '',
                status=stop.get('status') or TripStop.STATUS_CONFIRMED,
                sort_order=j,
            )
    return trip, True
